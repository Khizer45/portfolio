from alembic import command
from alembic.util.exc import AutogenerateDiffsDetected

from app.tests.conftest import alembic_config


def test_models_and_migrations_are_in_sync(engine):
    """Fails if a model was changed without generating a migration."""
    try:
        command.check(alembic_config())
    except AutogenerateDiffsDetected as exc:  # pragma: no cover - failure path
        raise AssertionError(f"Models differ from migrations; run `alembic revision --autogenerate`.\n{exc}") from exc
